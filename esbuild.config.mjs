import esbuild from 'esbuild';
import process from 'process';
import builtins from 'builtin-modules';
import { copyFileSync, mkdirSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === 'production';
const root = dirname(fileURLToPath(import.meta.url));
const vaultPluginDir = join(root, '../SpeakeasyVPN/.obsidian/plugins/obsidian-gitlab');

function publishArtifacts() {
	mkdirSync(vaultPluginDir, { recursive: true });
	for (const file of ['main.js', 'manifest.json', 'styles.css']) {
		copyFileSync(join(root, file), join(vaultPluginDir, file));
	}
	console.log(`Copied plugin to ${vaultPluginDir}`);
}

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: ['src/main.ts'],
	bundle: true,
	external: [
		'obsidian',
		'electron',
		'@codemirror/autocomplete',
		'@codemirror/collab',
		'@codemirror/commands',
		'@codemirror/language',
		'@codemirror/lint',
		'@codemirror/search',
		'@codemirror/state',
		'@codemirror/view',
		'@lezer/common',
		'@lezer/highlight',
		'@lezer/lr',
		...builtins,
	],
	format: 'cjs',
	platform: 'browser',
	loader: {
		'.svg': 'text',
	},
	target: 'es2018',
	logLevel: 'info',
	sourcemap: prod ? false : 'inline',
	treeShaking: true,
	outfile: 'main.js',
	minify: prod,
	plugins: [
		{
			name: 'rate-limiter-memory-only',
			setup(build) {
				build.onResolve({ filter: /^rate-limiter-flexible$/ }, () => ({
					path: join(root, 'src/shims/rate-limiter-flexible.js'),
				}));
			},
		},
		{
			name: 'publish-obsidian',
			setup(build) {
				build.onEnd((result) => {
					if (result.errors.length === 0) publishArtifacts();
				});
			},
		},
	],
});

if (prod) {
	await context.rebuild();
	process.exit(0);
} else {
	await context.watch();
}
